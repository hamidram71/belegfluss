"""German bank and tax identifiers: IBAN and USt-IdNr (VAT ID).

Both are generated by the synthetic data generator and validated deterministically by the
matching pipeline. The checksums are implemented here instead of pulling in a dependency,
because they are small and well specified.
"""

import re

_IBAN_DE = re.compile(r"^DE\d{20}$")
_IBAN_ANY = re.compile(r"^[A-Z]{2}\d{2}[A-Z0-9]{11,30}$")
_VAT_DE = re.compile(r"^DE[1-9]\d{8}$")


def _iban_mod97(rearranged: str) -> int:
    digits = "".join(str(int(ch, 36)) for ch in rearranged)
    return int(digits) % 97


def german_iban(bank_code: str, account_number: str) -> str:
    """Build a valid German IBAN from an 8-digit bank code (BLZ) and an account number."""
    if not (bank_code.isdigit() and len(bank_code) == 8):
        raise ValueError("bank_code must be 8 digits")
    if not (account_number.isdigit() and 1 <= len(account_number) <= 10):
        raise ValueError("account_number must be 1-10 digits")
    bban = bank_code + account_number.zfill(10)
    check = 98 - _iban_mod97(bban + "DE00")
    return f"DE{check:02d}{bban}"


def is_valid_iban(iban: str) -> bool:
    """Validate an IBAN with the ISO 13616 mod-97 check; German IBANs must have 22 characters."""
    compact = iban.replace(" ", "").upper()
    if compact.startswith("DE") and not _IBAN_DE.match(compact):
        return False
    if not _IBAN_ANY.match(compact):
        return False
    return _iban_mod97(compact[4:] + compact[:4]) == 1


def format_iban(iban: str) -> str:
    """Group an IBAN in blocks of four characters for printing."""
    compact = iban.replace(" ", "")
    return " ".join(compact[i : i + 4] for i in range(0, len(compact), 4))


def german_vat_check_digit(first_eight: str) -> int:
    """Check digit of a German USt-IdNr (ISO 7064, MOD 11,10)."""
    if not (first_eight.isdigit() and len(first_eight) == 8):
        raise ValueError("expected 8 digits")
    product = 10
    for ch in first_eight:
        total = (int(ch) + product) % 10
        if total == 0:
            total = 10
        product = (2 * total) % 11
    check = 11 - product
    return 0 if check == 10 else check


def german_vat_id(first_eight: str) -> str:
    """Build a valid German USt-IdNr from 8 digits (the first digit must not be 0)."""
    if first_eight.startswith("0"):
        raise ValueError("a German VAT ID never starts with 0")
    return f"DE{first_eight}{german_vat_check_digit(first_eight)}"


def is_valid_german_vat_id(vat_id: str) -> bool:
    """Validate format and check digit of a German USt-IdNr such as ``DE136695976``."""
    compact = vat_id.replace(" ", "").upper()
    if not _VAT_DE.match(compact):
        return False
    return german_vat_check_digit(compact[2:10]) == int(compact[10])
